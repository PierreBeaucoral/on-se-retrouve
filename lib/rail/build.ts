// Turns a GTFS feed into the per-date rail tables served by the static app.
// Kept separate from the CLI so the pipeline is testable on a synthetic feed.
import { servedStations, stationsForPlace, tripsOnDate, type Feed } from "./gtfs.ts";
import { crowKm, isRegionalBrand, legFare, terFare, type FareTable, type TerModel } from "./fares.ts";
import { buildNetwork, journeyTo, search, type Footpath, type Journey, type Network } from "./raptor.ts";

export type PlaceLike = { id: string; name: string; stations?: string[] };
// One train: [from station index, to station index, dep, arr (minutes after midnight), brand, train number, fare min, fare max,
// fare source: 0 published, 1 TER estimate, 2 TER 2025 fare]. Fares are null when unknown (foreign operators, unlisted pairs).
export type PackedSegment = [number, number, number, number, string, string, number | null, number | null, 0 | 1 | 2];
export type RailEntry = { m: number; d: number; a: number; t: number; l: PackedSegment[] }; // minutes, dep, arr, transfers, trains
// "origin|dest" -> every journey of the day that no other one beats (none leaves later and arrives as early or
// earlier), sorted by departure. For any requested time, the first one leaving at or after it arrives first.
export type RailTable = Record<string, RailEntry[]>;
export type RailDay = { date: string; range: [string, string]; stations: string[]; legs: RailTable };
export type BuildOptions = {
  range?: [string, string]; // departures considered, "HH:MM"
  maxMinutes?: number;
  minTransferMinutes?: number;
  maxTransfers?: number;
  intraCityMinutes?: Record<string, number>;
  defaultIntraCityMinutes?: number;
  stationOverrides?: Record<string, string[]>;
  fares?: FareTable;
  ter?: TerModel;
};

export const DEFAULT_RANGE: [string, string] = ["05:00", "23:00"];
export const DEFAULT_MAX_TRANSFERS = 3;

// Places carrying an explicit station list (generated by scripts/build-places.ts) use it; the others
// fall back to name matching. Only stations served by rail trips are kept.
export function resolvePlaceStations(feed: Feed, places: PlaceLike[], overrides: Record<string, string[]> = {}): Map<string, string[]> {
  const served = servedStations(feed.trips);
  const map = new Map<string, string[]>();
  for (const p of places) {
    const explicit = p.stations?.length ? { ...overrides, [p.name]: p.stations } : overrides;
    const stations = stationsForPlace(feed, p.name, served, explicit).map((s) => s.id);
    if (stations.length) map.set(p.id, stations);
  }
  return map;
}

export function intraCityFootpaths(placeStations: Map<string, string[]>, minutes: Record<string, number> = {}, fallback = 30): Footpath[] {
  const paths: Footpath[] = [];
  for (const [place, stations] of placeStations) {
    const seconds = (minutes[place] ?? fallback) * 60;
    for (const from of stations) for (const to of stations) if (from !== to) paths.push({ from, to, seconds });
  }
  return paths;
}

export function clockSeconds(time: string): number {
  const m = /^(\d{2}):(\d{2})$/.exec(time);
  if (!m) throw new Error(`Heure invalide : ${time}`);
  return Number(m[1]) * 3600 + Number(m[2]) * 60;
}

export function buildRailDay(feed: Feed, date: string, placeStations: Map<string, string[]>, options: BuildOptions = {}): RailDay {
  const range = options.range ?? DEFAULT_RANGE;
  const [from, to] = range.map(clockSeconds);
  const maxSeconds = (options.maxMinutes ?? 2880) * 60;
  const minTransferSeconds = (options.minTransferMinutes ?? 10) * 60;
  const maxRounds = (options.maxTransfers ?? DEFAULT_MAX_TRANSFERS) + 1;
  const trips = tripsOnDate(feed, date.replace(/-/g, ""));
  const tripById = new Map(trips.map((t) => [t.id, t]));
  const network = buildNetwork(trips, intraCityFootpaths(placeStations, options.intraCityMinutes, options.defaultIntraCityMinutes));
  const stationNames: string[] = [];
  const stationIndexByName = new Map<string, number>();
  const nameIndex = (id: string) => {
    const name = feed.stations.get(id)?.name ?? id;
    let i = stationIndexByName.get(name);
    if (i === undefined) { i = stationNames.length; stationNames.push(name); stationIndexByName.set(name, i); }
    return i;
  };
  const pack = (j: Journey): RailEntry => {
    const l = j.legs.map((leg): PackedSegment => {
      const trip = tripById.get(leg.tripId);
      const published = options.fares && trip ? legFare(options.fares, trip.brand, leg.from, leg.to) : undefined;
      const a = feed.stations.get(leg.from), b = feed.stations.get(leg.to);
      const ter = !published && options.ter && trip && isRegionalBrand(trip.brand) && a && b ? terFare(options.ter, leg.from, leg.to, crowKm(a, b)) : undefined;
      const fare = published ?? ter?.fare;
      return [nameIndex(leg.from), nameIndex(leg.to), Math.round(leg.dep / 60), Math.round(leg.arr / 60), trip?.brand ?? "", trip?.number ?? "", fare?.[0] ?? null, fare?.[1] ?? null, ter ? (ter.source === "ter2025" ? 2 : 1) : 0];
    });
    return { m: Math.round((j.arrival - j.departure) / 60), d: Math.round(j.departure / 60), a: Math.round(j.arrival / 60), t: j.transfers, l };
  };
  const legs: RailTable = {};
  for (const [origin, originStations] of placeStations) {
    // Range query: one earliest-arrival search per distinct departure time at the origin inside the range.
    const found = new Map<string, Journey[]>();
    for (const departure of originDepartures(network, originStations, from, to)) {
      const result = search(network, originStations, departure, { maxRounds, minTransferSeconds });
      if (!result) continue;
      for (const [dest, destStations] of placeStations) {
        if (dest === origin) continue;
        const j = journeyTo(result, destStations);
        if (!j || j.departure > to || j.arrival - j.departure > maxSeconds) continue;
        let list = found.get(dest);
        if (!list) found.set(dest, (list = []));
        list.push(j);
      }
    }
    for (const [dest, journeys] of found) legs[`${origin}|${dest}`] = paretoJourneys(journeys).map(pack);
  }
  return { date, range, stations: stationNames, legs };
}

// Journeys no other one beats: walking from the latest departure backwards, keep a journey only if it
// arrives strictly earlier than every later-leaving one (equal departure: earliest arrival, then fewest
// changes). Returned by departure, so arrivals increase too.
export function paretoJourneys<J extends { departure: number; arrival: number; transfers: number }>(journeys: J[]): J[] {
  const sorted = [...journeys].sort((a, b) => b.departure - a.departure || a.arrival - b.arrival || a.transfers - b.transfers);
  const kept: J[] = [];
  let best = Infinity;
  for (const j of sorted) if (j.arrival < best) { best = j.arrival; kept.push(j); }
  return kept.reverse();
}

// File format of public/rail/<date>/<origin>.json. Each distinct train is stored once (`segments`), journeys are
// lists of segment indices, and each destination maps to its journeys sorted by departure (see RailTable).
// A stored train is [from, to, dep, arr, brand index, number] plus [fare min, fare max] when known, plus 1 (TER estimate)
// or 2 (TER 2025 fare) when the fare is not a current SNCF publication.
export type StoredSegment = [number, number, number, number, number, string] | [number, number, number, number, number, string, number, number] | [number, number, number, number, number, string, number, number, 1 | 2];
export type RailOriginFile = { date: string; origin: string; range: [string, string]; stations: string[]; brands: string[]; segments: StoredSegment[]; journeys: number[][]; legs: Record<string, number[]> };

export function packOrigin(day: RailDay, origin: string): RailOriginFile {
  const brands: string[] = [];
  const segments: StoredSegment[] = [];
  const journeys: number[][] = [];
  const seenSegment = new Map<string, number>();
  const seenJourney = new Map<string, number>();
  const legs: Record<string, number[]> = {};
  const brandIndex = (b: string) => { let i = brands.indexOf(b); if (i < 0) { i = brands.length; brands.push(b); } return i; };
  const intern = <T>(seen: Map<string, number>, list: T[], item: T) => { const id = JSON.stringify(item); let i = seen.get(id); if (i === undefined) { i = list.length; list.push(item); seen.set(id, i); } return i; };
  for (const [key, entries] of Object.entries(day.legs)) {
    if (!key.startsWith(`${origin}|`)) continue;
    legs[key.slice(origin.length + 1)] = entries.map((entry) => intern(seenJourney, journeys, entry.l.map(([from, to, dep, arr, brand, number, min, max, source]) =>
      intern(seenSegment, segments, min === null || max === null ? [from, to, dep, arr, brandIndex(brand), number] as StoredSegment : source ? [from, to, dep, arr, brandIndex(brand), number, min, max, source] as StoredSegment : [from, to, dep, arr, brandIndex(brand), number, min, max] as StoredSegment))));
  }
  return { date: day.date, origin, range: day.range, stations: day.stations, brands, segments, journeys, legs };
}

// Distinct boarding times at the given stations within [from, to], plus `from` itself.
export function originDepartures(network: Network, stations: string[], from: number, to: number): number[] {
  const times = new Set<number>([from]);
  for (const id of stations) {
    const s = network.stationIndex.get(id);
    if (s === undefined) continue;
    for (const { pattern, index } of network.patternsAtStation[s]) {
      for (const trip of network.patterns[pattern].trips) {
        const dep = trip.dep[index];
        if (trip.board[index] && dep >= from && dep <= to) times.add(dep);
      }
    }
  }
  return [...times].sort((a, b) => a - b);
}

// Calendar dates (YYYY-MM-DD) for the requested weekdays over the coming weeks, from a start date.
export function upcomingDates(from: string, weeks: number, weekdays: number[]): string[] {
  const start = new Date(`${from}T00:00:00Z`);
  if (!Number.isFinite(start.getTime())) throw new Error(`Date de départ invalide : ${from}`);
  const out: string[] = [];
  for (let i = 0; i < weeks * 7; i++) {
    const d = new Date(start); d.setUTCDate(start.getUTCDate() + i);
    if (weekdays.includes(d.getUTCDay())) out.push(d.toISOString().slice(0, 10));
  }
  return out;
}
